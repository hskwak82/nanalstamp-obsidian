// 언어 적용: 설정이 auto면 자동감지, 아니면 강제(en/ko). t/tpl 재설정.
// (구 applyLang(s: AttestSettings) — AttestSettings 역참조를 끊으려 설정값만 받는다.)
export function setLang(pref: "auto" | "en" | "ko") {
  const lang: Lang = pref === "auto" ? pickLang() : (pref as Lang);
  t = STR[lang];
  tpl = TPL[lang];
}

// statement("reviewed"|"approved") → 현재 언어 라벨(np-verify: 점검함/승인함).
export function reviewVerdictLabel(statement: string): string {
  if (statement === "approved") return t.reviewApproved;
  if (statement === "reviewed") return t.reviewReviewed;
  return statement;
}
